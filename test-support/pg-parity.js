// Schema parity check: the PostgreSQL baseline (src/pg/schema/001_baseline.sql) against the FINAL SQLite schema
// (src/migrations.js 1-17 applied to an in-memory database). Used by test/pg/schema-parity.test.js.
//
// Both schemas are introspected into the same shape — per table: ordered columns (type, nullability, default,
// collation, identity), primary key, foreign keys (with ON DELETE / ON UPDATE), CHECK constraints and indexes (unique
// flag, key expressions, partial WHERE) — and compared. Expressions (defaults, CHECKs, index keys/predicates) are
// compared after canonicalization: SQL keywords lower-cased (string literals untouched), PostgreSQL's added casts and
// parentheses removed, `x = ANY (ARRAY[...])` read as `x IN (...)`, SQLite `GLOB 'p'` read as the equivalent anchored
// regex `~ '^p$'`, and both "now as UTC text" defaults read as one token.
//
// TRANSLATION RULES (equivalences, not differences):
//   INTEGER -> integer · REAL -> double precision · TEXT (BINARY) -> text COLLATE "C" (byte order, like BINARY)
//   INTEGER PRIMARY KEY AUTOINCREMENT -> integer GENERATED BY DEFAULT AS IDENTITY
//   DEFAULT (datetime('now')) -> to_char(statement_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')
//   x GLOB 'pattern' -> x ~ '^pattern$' (same character classes)
//   a NOCASE column inside an index key -> lower(column) (under COLLATE "C", lower() folds ASCII only, like NOCASE)
// Anything else that differs is a DIFFERENCE, and the check fails unless ALLOW_LIST explains it. An allow-list entry
// that no longer matches any difference also fails the check (so the list cannot rot).
const Database = require('better-sqlite3');
const { runMigrations: runSqliteMigrations } = require('../src/migrate');
const sqliteMigrations = require('../src/migrations');

const NOCASE_REASON = 'COLLATE NOCASE has no exact PostgreSQL column equivalent (ICU case-insensitive collations fold Unicode, '
  + 'NOCASE folds ASCII only). The column is text COLLATE "C" with a UNIQUE index on lower(column), which enforces the same '
  + 'uniqueness (lower() under "C" folds ASCII only). Plain `=`, ORDER BY and LIKE on this column are case-sensitive in '
  + 'PostgreSQL, so Slice 3+ queries that relied on NOCASE must compare lower(column) = lower($1) (index-backed).';

const ALLOW_LIST = [
  { kind: 'missing-table', table: 'sqlite_sequence', reason: "SQLite's internal AUTOINCREMENT bookkeeping table, not an app table. PostgreSQL identity columns keep their own sequences (the Slice 7 data copy must advance them past copied ids)." },
  { kind: 'nocase', table: 'assets', column: 'tag', reason: NOCASE_REASON },
  { kind: 'nocase', table: 'accounts', column: 'login_email', reason: NOCASE_REASON },
  { kind: 'nocase', table: 'employees', column: 'work_email', reason: NOCASE_REASON },
  { kind: 'pk-not-null', table: '*', column: '*', reason: 'SQLite reports PRIMARY KEY columns as nullable (an INTEGER PRIMARY KEY turns NULL into a new rowid; a TEXT PRIMARY KEY accepting NULL is a legacy SQLite quirk the app never relies on). PostgreSQL primary keys are always NOT NULL.' },
  { kind: 'rowid-alias', table: 'schema_migrations', column: 'id', reason: 'SQLite assigns a rowid when an INTEGER PRIMARY KEY is omitted; PostgreSQL has no implicit value here. Both runners always insert the migration id explicitly.' },
  { kind: 'rowid-alias', table: 'asset_tag_counter', column: 'id', reason: 'Single-row table (CHECK id = 1); the row is always written with id 1 explicitly, so the implicit rowid is never used.' },
  { kind: 'type', table: 'sessions', column: 'expires', reason: 'Holds epoch MILLISECONDS (Date.now()), which exceed int4; bigint keeps every value. The pool returns int8 as a JS number, as better-sqlite3 does.' },
];

const EXPECTED_TYPE = { INTEGER: 'integer', TEXT: 'text', REAL: 'double precision' };
const FK_ACTION = { a: 'NO ACTION', r: 'RESTRICT', c: 'CASCADE', n: 'SET NULL', d: 'SET DEFAULT' };
const NOW_SQLITE = "datetime('now')";
const NOW_PG = "to_char(statement_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')";

// ---------- small SQL text helpers ----------

// Index of the ')' matching the '(' at `open`, skipping quoted text.
function matchParen(s, open) {
  let depth = 0;
  for (let i = open; i < s.length; i++) {
    const ch = s[i];
    if (ch === "'" || ch === '"') {
      const q = ch;
      for (i++; i < s.length && !(s[i] === q && s[i + 1] !== q); i++) if (s[i] === q) i++;
      continue;
    }
    if (ch === '(') depth++;
    else if (ch === ')' && --depth === 0) return i;
  }
  throw new Error(`unbalanced parentheses in: ${s}`);
}

// Splits on commas at parenthesis depth 0, outside quotes.
function splitTopLevel(s) {
  const parts = [];
  let depth = 0;
  let start = 0;
  for (let i = 0; i < s.length; i++) {
    const ch = s[i];
    if (ch === "'" || ch === '"') {
      const q = ch;
      for (i++; i < s.length && !(s[i] === q && s[i + 1] !== q); i++) if (s[i] === q) i++;
      continue;
    }
    if (ch === '(') depth++;
    else if (ch === ')') depth--;
    else if (ch === ',' && depth === 0) { parts.push(s.slice(start, i).trim()); start = i + 1; }
  }
  parts.push(s.slice(start).trim());
  return parts.filter(Boolean);
}

// Every `CHECK ( ... )` body in a column or table definition.
function checkBodies(def) {
  const out = [];
  const re = /\bCHECK\s*\(/gi;
  let m;
  while ((m = re.exec(def))) {
    const open = m.index + m[0].length - 1;
    const close = matchParen(def, open);
    out.push(def.slice(open + 1, close));
    re.lastIndex = close;
  }
  return out;
}

function globToRegex(glob) {
  let re = '^';
  for (let i = 0; i < glob.length; i++) {
    const ch = glob[i];
    if (ch === '[') { const end = glob.indexOf(']', i); re += glob.slice(i, end + 1); i = end; }
    else if (ch === '*') re += '.*';
    else if (ch === '?') re += '.';
    else re += /[.^$+(){}|\\]/.test(ch) ? `\\${ch}` : ch;
  }
  return `${re}$`;
}

// Canonical form of an SQL expression (see the header). Literals are protected while the rest is rewritten.
function canonCore(sql) {
  const literals = [];
  let code = String(sql).replace(/'(?:[^']|'')*'/g, (lit) => { literals.push(lit); return `\u0000${literals.length - 1}\u0000`; });
  code = code.replace(/"([^"]*)"/g, '$1').toLowerCase();
  code = code.replace(/::(?:text|integer|bigint|numeric|double precision|character varying|timestamp without time zone|timestamp with time zone)(?:\[\])?/g, '');
  code = code.replace(/\s+collate\s+(?:c|nocase|binary)\b/g, '');
  code = code.replace(/trim\(\s*both\s+from\s+/g, 'trim(');
  code = code.replace(/=\s*any\s*\(\s*array\[([^\]]*)\]\s*\)/g, ' in ($1)');
  code = code.replace(/<>\s*all\s*\(\s*array\[([^\]]*)\]\s*\)/g, ' not in ($1)');
  code = code.replace(/\s+glob\s+\u0000(\d+)\u0000/g, (_, n) => {
    literals[n] = `'${globToRegex(literals[n].slice(1, -1).replace(/''/g, "'")).replace(/'/g, "''")}'`;
    return ` ~ \u0000${n}\u0000`;
  });
  code = code.replace(/[()\s]/g, '');
  return code.replace(/\u0000(\d+)\u0000/g, (_, n) => literals[n]);
}

const NOW_FORMS = new Set([canonCore(NOW_SQLITE), canonCore(NOW_PG)]);

function canon(sql) {
  if (sql === null || sql === undefined) return null;
  const c = canonCore(sql);
  return NOW_FORMS.has(c) ? '<utc-now-text>' : c;
}

// ---------- SQLite side ----------

function buildSqliteReference() {
  const db = new Database(':memory:');
  db.pragma('foreign_keys = ON');
  runSqliteMigrations(db, sqliteMigrations);
  return db;
}

function describeSqlite(db) {
  const tables = {};
  for (const { name, sql } of db.prepare("SELECT name, sql FROM sqlite_master WHERE type = 'table' ORDER BY name").all()) {
    const open = sql.indexOf('(');
    const defs = splitTopLevel(sql.slice(open + 1, matchParen(sql, open)));
    const colDefs = new Map();
    const checks = [];
    for (const def of defs) {
      if (/^(CHECK|CONSTRAINT|UNIQUE|PRIMARY|FOREIGN)\b/i.test(def)) checks.push(...checkBodies(def));
      else {
        colDefs.set(def.split(/\s+/)[0].replace(/"/g, ''), def);
        checks.push(...checkBodies(def));
      }
    }
    const info = db.prepare(`PRAGMA table_xinfo("${name}")`).all();
    const pkCols = info.filter((c) => c.pk > 0).sort((a, b) => a.pk - b.pk).map((c) => c.name);
    const columns = info.map((c) => {
      const def = colDefs.get(c.name) || '';
      const rowidAlias = pkCols.length === 1 && pkCols[0] === c.name && c.type.toUpperCase() === 'INTEGER';
      return {
        name: c.name,
        type: c.type.toUpperCase(),
        notNull: c.notnull === 1,
        pk: c.pk > 0,
        default: canon(c.dflt_value),
        nocase: /\bCOLLATE\s+NOCASE\b/i.test(def),
        autoincrement: /\bAUTOINCREMENT\b/i.test(def),
        rowidAlias: rowidAlias && !/\bAUTOINCREMENT\b/i.test(def),
      };
    });
    const nocase = new Set(columns.filter((c) => c.nocase).map((c) => c.name));
    const keyOf = (k) => (nocase.has(k.trim()) ? canon(`lower(${k.trim()})`) : canon(k));

    const fks = db.prepare(`PRAGMA foreign_key_list("${name}")`).all()
      .map((f) => `${f.from} -> ${f.table}(${f.to}) on delete ${f.on_delete} on update ${f.on_update}`).sort();

    const indexes = [];
    for (const ix of db.prepare(`PRAGMA index_list("${name}")`).all()) {
      if (ix.origin === 'pk') continue;
      if (ix.origin === 'c') {
        const isql = db.prepare("SELECT sql FROM sqlite_master WHERE type = 'index' AND name = ?").get(ix.name).sql;
        const iopen = isql.indexOf('(');
        const iclose = matchParen(isql, iopen);
        const where = /^\s*WHERE\s+([\s\S]*)$/i.exec(isql.slice(iclose + 1));
        indexes.push({ name: ix.name, auto: false, unique: ix.unique === 1, keys: splitTopLevel(isql.slice(iopen + 1, iclose)).map(keyOf), where: where ? canon(where[1]) : null });
      } else {
        const keys = db.prepare(`PRAGMA index_xinfo("${ix.name}")`).all().filter((k) => k.key === 1)
          .map((k) => (k.coll && k.coll.toUpperCase() === 'NOCASE' ? canon(`lower(${k.name})`) : canon(k.name)));
        indexes.push({ name: ix.name, auto: true, unique: ix.unique === 1, keys, where: null });
      }
    }
    tables[name] = { columns, pk: pkCols, fks, checks: checks.map(canon).sort(), indexes };
  }
  return tables;
}

// ---------- PostgreSQL side ----------

async function describePg(client) {
  const tables = {};
  const cols = await client.query(`
    SELECT c.relname AS table, a.attname AS name, format_type(a.atttypid, a.atttypmod) AS type, a.attnotnull AS not_null,
           pg_get_expr(d.adbin, d.adrelid) AS default, a.attidentity AS identity, co.collname AS collation
    FROM pg_class c
    JOIN pg_namespace n ON n.oid = c.relnamespace
    JOIN pg_attribute a ON a.attrelid = c.oid AND a.attnum > 0 AND NOT a.attisdropped
    LEFT JOIN pg_attrdef d ON d.adrelid = c.oid AND d.adnum = a.attnum
    LEFT JOIN pg_collation co ON co.oid = a.attcollation
    WHERE n.nspname = current_schema() AND c.relkind = 'r'
    ORDER BY c.relname, a.attnum`);
  for (const r of cols.rows) {
    tables[r.table] ||= { columns: [], pk: [], fks: [], checks: [], indexes: [] };
    tables[r.table].columns.push({ name: r.name, type: r.type, notNull: r.not_null, default: canon(r.default), identity: r.identity, collation: r.collation });
  }
  const cons = await client.query(`
    SELECT c.relname AS table, con.contype, pg_get_constraintdef(con.oid) AS def,
           ARRAY(SELECT a.attname::text FROM unnest(con.conkey) WITH ORDINALITY k(attnum, ord)
                 JOIN pg_attribute a ON a.attrelid = con.conrelid AND a.attnum = k.attnum ORDER BY k.ord) AS cols,
           ft.relname AS ref_table,
           ARRAY(SELECT a.attname::text FROM unnest(con.confkey) WITH ORDINALITY k(attnum, ord)
                 JOIN pg_attribute a ON a.attrelid = con.confrelid AND a.attnum = k.attnum ORDER BY k.ord) AS ref_cols,
           con.confdeltype, con.confupdtype
    FROM pg_constraint con
    JOIN pg_class c ON c.oid = con.conrelid
    JOIN pg_namespace n ON n.oid = c.relnamespace
    LEFT JOIN pg_class ft ON ft.oid = con.confrelid
    WHERE n.nspname = current_schema() AND con.contype IN ('p', 'f', 'c')`);
  for (const r of cons.rows) {
    const t = tables[r.table];
    if (r.contype === 'p') t.pk = r.cols;
    else if (r.contype === 'f') t.fks.push(`${r.cols.join(', ')} -> ${r.ref_table}(${r.ref_cols.join(', ')}) on delete ${FK_ACTION[r.confdeltype]} on update ${FK_ACTION[r.confupdtype]}`);
    else t.checks.push(canon(r.def.replace(/^CHECK\s*/i, '')));
  }
  const idx = await client.query(`
    SELECT t.relname AS table, i.relname AS name, x.indisunique AS unique, x.indisprimary AS primary,
           ARRAY(SELECT pg_get_indexdef(x.indexrelid, k, true) FROM generate_series(1, x.indnkeyatts) k ORDER BY k) AS keys,
           pg_get_expr(x.indpred, x.indrelid, true) AS where
    FROM pg_index x
    JOIN pg_class i ON i.oid = x.indexrelid
    JOIN pg_class t ON t.oid = x.indrelid
    JOIN pg_namespace n ON n.oid = t.relnamespace
    WHERE n.nspname = current_schema()`);
  for (const r of idx.rows) {
    if (r.primary) continue;
    tables[r.table].indexes.push({ name: r.name, unique: r.unique, keys: r.keys.map(canon), where: canon(r.where) });
  }
  for (const t of Object.values(tables)) { t.fks.sort(); t.checks.sort(); }
  return tables;
}

// ---------- comparison ----------

function multisetDiff(a, b) {
  const rest = [...b];
  const missing = [];
  for (const x of a) {
    const i = rest.indexOf(x);
    if (i === -1) missing.push(x); else rest.splice(i, 1);
  }
  return { missing, extra: rest };
}

// Every difference between the two schemas, as { kind, table, column?, detail }. Pure.
function diffSchemas(sqlite, pg) {
  const diffs = [];
  const add = (kind, table, column, detail) => diffs.push({ kind, table, column: column ?? null, detail });
  for (const table of Object.keys(sqlite)) if (!pg[table]) add('missing-table', table, null, 'table exists in SQLite only');
  for (const table of Object.keys(pg)) if (!sqlite[table]) add('extra-table', table, null, 'table exists in PostgreSQL only');

  for (const table of Object.keys(sqlite).filter((t) => pg[t])) {
    const s = sqlite[table];
    const p = pg[table];
    const sNames = s.columns.map((c) => c.name);
    const pNames = p.columns.map((c) => c.name);
    for (const n of sNames) if (!pNames.includes(n)) add('missing-column', table, n, 'column exists in SQLite only');
    for (const n of pNames) if (!sNames.includes(n)) add('extra-column', table, n, 'column exists in PostgreSQL only');
    const common = sNames.filter((n) => pNames.includes(n));
    if (common.join() !== pNames.filter((n) => sNames.includes(n)).join()) add('column-order', table, null, `SQLite ${sNames.join(', ')} | PostgreSQL ${pNames.join(', ')}`);

    for (const name of common) {
      const sc = s.columns.find((c) => c.name === name);
      const pc = p.columns.find((c) => c.name === name);
      const expectedType = EXPECTED_TYPE[sc.type];
      if (pc.type !== expectedType) add('type', table, name, `SQLite ${sc.type} expects ${expectedType || '(no mapping)'}, PostgreSQL has ${pc.type}`);
      if (pc.type === 'text' && pc.collation !== 'C') add('collation', table, name, `PostgreSQL text column has collation ${pc.collation}, expected "C"`);
      if (sc.nocase) add('nocase', table, name, 'SQLite COLLATE NOCASE column');
      if (sc.notNull !== pc.notNull) {
        if (sc.pk && !sc.notNull && pc.notNull) add('pk-not-null', table, name, 'primary key column: nullable in SQLite, NOT NULL in PostgreSQL');
        else add('nullability', table, name, `SQLite ${sc.notNull ? 'NOT NULL' : 'NULL'}, PostgreSQL ${pc.notNull ? 'NOT NULL' : 'NULL'}`);
      }
      if (sc.autoincrement) {
        if (pc.identity !== 'd') add('identity', table, name, `AUTOINCREMENT expects GENERATED BY DEFAULT AS IDENTITY, PostgreSQL identity is "${pc.identity || 'none'}"`);
      } else if (pc.identity) add('identity', table, name, `PostgreSQL identity "${pc.identity}" without SQLite AUTOINCREMENT`);
      if (sc.rowidAlias && !pc.identity) add('rowid-alias', table, name, 'INTEGER PRIMARY KEY without AUTOINCREMENT (rowid alias); PostgreSQL has a plain primary key');
      if (sc.default !== pc.default) add('default', table, name, `SQLite ${sc.default} | PostgreSQL ${pc.default}`);
    }

    if (s.pk.join() !== p.pk.join()) add('primary-key', table, null, `SQLite (${s.pk.join(', ')}) | PostgreSQL (${p.pk.join(', ')})`);
    const fk = multisetDiff(s.fks, p.fks);
    for (const f of fk.missing) add('missing-fk', table, null, f);
    for (const f of fk.extra) add('extra-fk', table, null, f);
    const ck = multisetDiff(s.checks, p.checks);
    for (const c of ck.missing) add('missing-check', table, null, c);
    for (const c of ck.extra) add('extra-check', table, null, c);

    const pIdx = [...p.indexes];
    const take = (pred) => { const i = pIdx.findIndex(pred); return i === -1 ? null : pIdx.splice(i, 1)[0]; };
    const same = (a, b) => a.unique === b.unique && a.keys.join() === b.keys.join() && a.where === b.where;
    for (const si of s.indexes.filter((i) => !i.auto)) {
      const pi = take((x) => x.name === si.name);
      if (!pi) add('missing-index', table, null, `${si.name} (${si.keys.join(', ')})`);
      else if (!same(si, pi)) add('index', table, null, `${si.name}: SQLite ${JSON.stringify(si)} | PostgreSQL ${JSON.stringify(pi)}`);
    }
    for (const si of s.indexes.filter((i) => i.auto)) {
      const pi = take((x) => same(si, x));
      if (!pi) add('missing-index', table, null, `${si.unique ? 'UNIQUE ' : ''}(${si.keys.join(', ')}) [${si.name}]`);
    }
    for (const pi of pIdx) add('extra-index', table, null, `${pi.name} (${pi.keys.join(', ')})`);
  }
  return diffs;
}

const matches = (entry, d) => entry.kind === d.kind
  && (entry.table === '*' || entry.table === d.table)
  && (entry.column === undefined || entry.column === '*' || entry.column === d.column);

// { unexplained, explained: [{ ...diff, reason }], unusedAllowList }
function compareSchemas(sqlite, pg, allowList = ALLOW_LIST) {
  const explained = [];
  const unexplained = [];
  const used = new Set();
  for (const d of diffSchemas(sqlite, pg)) {
    const entry = allowList.find((e) => matches(e, d));
    if (entry) { used.add(entry); explained.push({ ...d, reason: entry.reason }); } else unexplained.push(d);
  }
  return { unexplained, explained, unusedAllowList: allowList.filter((e) => !used.has(e)) };
}

