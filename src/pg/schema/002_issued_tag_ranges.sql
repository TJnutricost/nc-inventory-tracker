-- Which prefix each claimed tag number was issued under (see SQLite migration 18, src/migrations.js). Fresh databases start with no
-- claims, so there is nothing to backfill; scripts/pg-copy.js carries the SQLite rows over.
CREATE TABLE issued_tag_ranges (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  prefix text COLLATE "C" NOT NULL,
  first_number integer NOT NULL CHECK (first_number >= 1),
  last_number integer NOT NULL,
  created_at text COLLATE "C" NOT NULL DEFAULT to_char(statement_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
  CHECK (last_number >= first_number)
);
